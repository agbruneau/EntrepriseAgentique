def _jour(d):
    d = int(_re.sub(r'\D', '', str(d)))
    return '1<sup>er</sup>' if d == 1 else str(d)


def _date(d):
    d = d.strip()
    if d in ('s.d.', 's. d.'):
        return 's. d.', None
    if _re.fullmatch(r'\d{4}(-\d{4})?', d):
        return d, None
    m = _re.fullmatch(r'(\d{4})-(\d{2})-(\d{2})', d)
    if m:
        return f'{m[1]}, {_jour(m[3])} {_MOIS[int(m[2]) - 1]}', None
    m = _re.fullmatch(r'(\d{4})-(\d{2})', d)
    if m:
        return f'{m[1]}, {_MOIS[int(m[2]) - 1]}', None
    m = _re.fullmatch(r'(\d{1,2})(?:er|<sup>er</sup>)?[ \xa0](' + _MR + r')[ \xa0](\d{4})', d)
    if m:
        return f'{m[3]}, {_jour(m[1])} {m[2]}', None
    m = _re.fullmatch(r'(' + _MR + r')[ \xa0](\d{4})', d)
    if m:
        return f'{m[2]}, {m[1]}', None
    m = _re.fullmatch(r'(\d{4}), (\d{1,2}(?:er|<sup>er</sup>)?) (' + _MR + r')', d)
    if m:
        return f'{m[1]}, {_jour(m[2])} {m[3]}', None
    m = _re.fullmatch(r'(\d{4}), (' + _MR + r')', d)
    if m:
        return d, None
    m = _re.fullmatch(r'consulté(?:e)? le (\d{1,2}) (' + _MR + r') (\d{4})', d)
    if m:
        return 's. d.', f'Consulté le {m[1]} {m[2]} {m[3]}.'
    m = _re.fullmatch(r'(\d{1,2}) (' + _MR + r') (\d{4}), mis à jour le (\d{1,2}) (' + _MR + r') (\d{4})', d)
    if m:
        return f'{m[3]}, {_jour(m[1])} {m[2]}; mis à jour le {m[4]} {m[5]} {m[6]}', None
    return d, None


def gabarit(n, t, complet=True):
    """Entrée de l'annexe G (texte après le numéro) au gabarit; rend (texte, catégorie)."""
    if n == 304 and t.startswith('SAE International. J3016'):
        t = t.replace('SAE International. J3016', 'SAE International (s. d.). J3016', 1)
    m = _re.search(r'\(([^()]*?)\)\. ', t)
    cat = 'C' if n in CAT_C else 'B' if n in CAT_B else 'A'
    if not m or '<a href' not in t[m.end():]:
        return t + f' (catégorie {cat})', cat
    auteur = t[:m.start()].rstrip(); d = m.group(1); rest = t[m.end():]
    i = rest.index('<a href'); body = rest[:i]; lien = rest[i:]
    nd, consulte = _date(d)
    if complet and _re.fullmatch(r'\d{4}', nd) and n not in NE_PAS_DEPLACER:
        mm = _re.search(r'(, |\(communiqué, |\. )(\d{1,2})(?:er|<sup>er</sup>)? (' + _MR + r') (' + nd + r')\)?\. ', body)
        if mm:
            seg = mm.group(0)
            nd = f'{nd}, {_jour(mm[2])} {mm[3]}'
            if seg.startswith('(communiqué'):
                body = body.replace(' ' + seg, ' [communiqué]. ', 1)
            else:
                body = body.replace(seg, '. ', 1)
            body = body.replace('. Communiqué. ', ' [communiqué]. ', 1)
            if body.endswith('. Communiqué. '):
                body = body[:-len('. Communiqué. ')] + ' [communiqué]. '
    auteur = AUTEURS.get(auteur, auteur)
    body = _re.sub(r'^<em>(.*?)</em>\.', r'\1.', body)
    if complet and n in EDITEUR:
        ed = EDITEUR[n]
        body = body.rstrip() + ' ' + (ed if ed.endswith('.') else ed + '.') + ' '
    if complet and n in APRES_TITRE:
        ed = APRES_TITRE[n]
        k = body.find('. ')
        body = body[:k + 2] + ed + '. ' + body[k + 2:]
    if not complet:
        # entrée réécrite en amont : éditeur ajouté seulement si l'entrée se réduit au titre (ou au titre
        # suivi d'une note reconnue), communiqué noté comme ailleurs dans l'annexe
        b = body.rstrip()
        if b.endswith('. Communiqué.'):
            b = b[:-len('. Communiqué.')] + ' [communiqué].'
        if n in EDITEUR:
            ed = EDITEUR[n]; ed_fin = ed if ed.endswith('.') else ed + '.'
            if '. ' not in b.replace('vs. ', 'vs ') and not b.endswith(' ' + ed_fin):
                b = b + ' ' + ed_fin
        if n in APRES_TITRE:
            ed = APRES_TITRE[n]
            k = b.find('. ')
            suite = b[k + 2:] if k >= 0 else ''
            if _re.match(r'(Même source|Argument d’éditeur|Site non officiel|Adresse)', suite):
                b = b[:k + 2] + ed + '. ' + suite
        body = b + ' '
    if not body.endswith(' '):
        body += ' '
    fin = lien + (' ' + consulte if consulte else '') + f' (catégorie {cat})'
    return f'{auteur} ({nd}). {body}{fin}', cat


def _empreinte(t):
    return _hashlib.sha1(t.encode('utf8')).hexdigest()[:16]


_LI = _re.compile(r'<li><strong><code>\[(\d+)\]</code></strong> (.*?)</li>', _re.S)


_ROLES = [('Fournisseur et déployeur. ', 'F, D'), ('Fournisseur. ', 'F'), ('Déployeur. ', 'D')]
_COLS = {'Tableau 44': 10, 'Tableau 49': 4, 'Tableau 54': 6, 'Tableau 69': 8}


def _rangees_ajoutees(s, retires):
    """Rangée ajoutée par un module antérieur, sans la colonne de ce module : colonne complétée."""
    for cap, ncol in _COLS.items():
        a = s.index('<table><caption>' + cap)
        b = s.index('</table>', a)
        t = s[a:b]
        for r in _re.findall(r'<tr><td>.*?</tr>', t, _re.S):
            c = _re.findall(r'<td>(.*?)</td>', r, _re.S)
            if len(c) == ncol:
                continue
            assert len(c) == ncol - (2 if cap == 'Tableau 69' else 1), (cap, r[:80])
            if cap == 'Tableau 49':
                role, exi = '—', c[1]
                for pref, rl in _ROLES:
                    if exi.startswith(pref):
                        role, exi = rl, exi[len(pref):]
                        break
                nr = f'<tr><td>{c[0]}</td><td>{role}</td><td>{exi}</td><td>{c[2]}</td></tr>'
            elif cap == 'Tableau 44':
                k = r.index('</td>') + 5
                nr = r[:k] + '<td>—</td>' + r[k:]
            elif cap == 'Tableau 54':
                k = r.index('</td>', r.index('</td>') + 5) + 5
                nr = r[:k] + '<td>Toutes</td>' + r[k:]
            else:
                raise AssertionError(f'tableau 69 : rangée ajoutée sans correspondance établie : {r[:80]}')
            t = t.replace(r, nr, 1)
            retires.append(r)
        s = s[:a] + t + s[b:]
    return s


def transformer(s):
    rangees = []
    s = _rangees_ajoutees(s, rangees)
    i = s.index('<h2>G Références</h2>')
    j = s.index('</ul>', i)
    seg = s[i:j]
    retires, nouveaux, vus = [], [], set()

    def un(m):
        n = int(m.group(1)); t = m.group(2); vus.add(n)
        if '(catégorie ' in t[-20:]:
            return m.group(0)
        complet = ORIGINE.get(n) == _empreinte(t)
        nt, _ = gabarit(n, t, complet)
        retires.append(m.group(0))
        return f'<li><strong><code>[{n}]</code></strong> {nt}</li>'

    seg = _LI.sub(un, seg)
    assert len(vus) == 473 and vus == set(range(1, 474)), f'annexe G : {len(vus)} entrées lues'
    return s[:i] + seg + s[j:], rangees + retires
